async function main() {
  const conn = await mysql.createConnection(process.env.DATABASE_URL);
  console.log(`Seeding ${CARDS.length} cards...`);

  // Clear existing entries first
  await conn.execute("DELETE FROM card_of_the_day_entries");
  console.log("Cleared existing entries.");

  // Assign dates starting from today
  const today = new Date();
  let inserted = 0;

  for (let i = 0; i < CARDS.length; i++) {
    const d = new Date(today);
    d.setDate(today.getDate() + i);
    const dateStr = d.toISOString().split("T")[0];
    const card = CARDS[i];

    try {
      await conn.execute(
        `INSERT INTO card_of_the_day_entries
          (date, characterName, characterRealName, characterTagline, characterBio, characterFacts,
           cardNumber, setName, setLabel, frontImageUrl, estimatedPrice, buzzNote,
           parallelType, printRun, serialNumber, cgcGrade, gradingCompany, isActive)
         VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1)`,
        [
          dateStr,
          card.characterName,
          card.characterRealName || null,
          card.characterTagline || null,
          card.characterBio || null,
          card.characterFacts || null,
          card.cardNumber || null,
          card.setName,
          card.setLabel || null,
          card.frontImageUrl || null,
          card.estimatedPrice || null,
          card.buzzNote || null,
          card.parallelType || null,
          card.printRun || null,
          card.serialNumber || null,
          card.cgcGrade || null,
          card.gradingCompany || null,
        ]
      );
      inserted++;
      console.log(`  [${i + 1}/${CARDS.length}] ${dateStr}: ${card.characterName} (${card.setLabel} ${card.parallelType})`);
    } catch (err) {
      console.error(`  ERROR on ${card.characterName}:`, err.message);
    }
  }

  console.log(`\nDone! Inserted ${inserted}/${CARDS.length} cards.`);
  await conn.end();
}

main().catch(console.error);
